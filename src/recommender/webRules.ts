export interface SectionTarget {
  id: string;
  title: string;
}

export interface TopicRule {
  id: string;
  lessonId: string;
  /** Curriculum order so foundational topics and prerequisites appear before practical/integration steps. */
  order: number;
  /** Phrases compared against accent- and case-normalized text (longest phrase wins inside a span). */
  synonyms: string[];
  section?: SectionTarget;
  /** Optional rule-specific section overrides for narrower synonyms. */
  sectionByPhrase?: Record<string, SectionTarget>;
  reason: string;
  practiceAction: string;
  successCriteria?: string;
  /** Lesson IDs to pull in before this lesson as helpful prerequisites when not already requested. */
  prerequisiteIds?: string[];
}

export interface ContextSignal {
  /** Normalized phrase that gives context (e.g. "frontend") without mandating a specific framework. */
  phrases: string[];
  /** Lesson IDs offered strictly as optional support suggestions when their own keywords weren't requested. */
  supportLessonIds: string[];
  reasonByLessonId: Record<string, string>;
}

